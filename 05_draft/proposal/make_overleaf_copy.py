#!/usr/bin/env python3
"""Generate an Overleaf-friendly proposal .tex from the local source.

`main.tex` uses local macOS/ZJU fonts when available. Overleaf normally does not
ship those fonts, so this script creates `main_overleaf.tex` using TeX Live
fonts that are available under Overleaf's XeLaTeX setup.
"""

from pathlib import Path


ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / "main.tex"
TARGET = ROOT / "main_overleaf.tex"


LOCAL_FONT_BLOCK = r"""\usepackage{fontspec}
\usepackage{xeCJK}
\setmainfont{Times New Roman}
\setCJKmainfont[AutoFakeBold=2.0]{STFangsong}
\newCJKfontfamily\fangsong[AutoFakeBold=2.0]{STFangsong}"""


OVERLEAF_FONT_BLOCK = r"""\usepackage{fontspec}
\usepackage[UTF8,fontset=fandol]{ctex}
\setmainfont{TeX Gyre Termes}
\setCJKmainfont[AutoFakeBold=2.0]{FandolFang-Regular}"""


LOCAL_BIB_BLOCK = r"""\bibliographystyle{plainnat}
\bibliography{../../02_literature/references}"""


OVERLEAF_BIB_BLOCK = r"""\bibliographystyle{plainnat}
\IfFileExists{references.bib}{%
  \bibliography{references}%
}{%
  \IfFileExists{../../02_literature/references.bib}{%
    \bibliography{../../02_literature/references}%
  }{%
    % No bibliography file found. In Overleaf, upload the project bibliography
    % as references.bib when citations are added.
  }%
}"""


def main() -> None:
    text = SOURCE.read_text()
    text = text.replace(
        "%  Compile with XeLaTeX/Tectonic, not pdfLaTeX.",
        "%  Overleaf copy: compile with XeLaTeX. Generated by make_overleaf_copy.py.",
    )
    text = text.replace(
        "\\documentclass[12pt,a4paper]{article}",
        "% OVERLEAF-FRIENDLY COPY. Edit main.tex, then regenerate this file.\n"
        "\\documentclass[12pt,a4paper]{article}",
        1,
    )
    if LOCAL_FONT_BLOCK not in text:
        raise SystemExit("Expected local font block was not found in main.tex")
    text = text.replace(LOCAL_FONT_BLOCK, OVERLEAF_FONT_BLOCK)
    if LOCAL_BIB_BLOCK not in text:
        raise SystemExit("Expected bibliography block was not found in main.tex")
    text = text.replace(LOCAL_BIB_BLOCK, OVERLEAF_BIB_BLOCK)
    TARGET.write_text(text)


if __name__ == "__main__":
    main()
